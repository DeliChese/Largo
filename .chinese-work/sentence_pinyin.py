def _needs_apostrophe(a: str, b: str) -> bool:
    return bool(b) and b[0].lower() in 'aoeāáǎàōóǒòēéěè'


def join_syllables(syllables: list[str]) -> str:
    out = ''
    for s in syllables:
        if not out:
            out = s
        elif _needs_apostrophe(out, s):
            out += '’' + s
        else:
            out += s
    return out


def build_vocab_lexicon(cards: list[dict]) -> tuple[dict[str, str], dict[str, str]]:
    lex = dict(EXTRA_COMPOUNDS)
    char_py = dict(BASE_CHAR_PINYIN)

    # First collect unambiguous single-char cards and multi-char cards
    for c in cards:
        term = c['term']
        py = c['phonetic'].split('/')[0].strip()
        if len(term) == 1:
            # Prefer non-neutral or main reading as default single char
            if term not in char_py:
                char_py[term] = py
        else:
            # Keep compound joined cleanly if multiple space-separated syllables unless 3+ words
            parts = py.split()
            if len(parts) == len([ch for ch in term if '\u4e00' <= ch <= '\u9fff']) and len(parts) <= 3:
                lex.setdefault(term, join_syllables(parts))
            else:
                lex.setdefault(term, py)
    return lex, char_py


def _capitalize_pinyin(text: str) -> str:
    # Capitalize start of sentence and after . ? ! “
    chars = list(text)
    cap_next = True
    i = 0
    while i < len(chars):
        ch = chars[i]
        if cap_next and ch.isalpha():
            chars[i] = ch.upper()
            cap_next = False
        elif ch in '.?!':
            cap_next = True
        elif not ch.isspace() and ch not in '“"\'‘':
            cap_next = False
        i += 1
    return ''.join(chars)


def sentence_to_pinyin(sentence: str, lex: dict[str, str], char_py: dict[str, str]) -> str:
    """Convert a Chinese sentence to spaced, punctuated Pinyin."""
    # Pre-tokenize fixed context expressions with sentinel markers \x00...\x01
    marked = sentence
    replacements: list[str] = []
    for pat, py in CONTEXT_FIXES:
        def _sub(m):
            idx = len(replacements)
            replacements.append(py)
            return f'\x00{idx}\x01'
        marked = re.sub(pat, _sub, marked)

    max_len = max((len(k) for k in lex), default=4)
    tokens: list[tuple[str, str]] = []  # (kind: 'word'|'punct'|'space', text)

    PUNCT_MAP = {
        '，': ', ',
        '。': '.',
        '？': '?',
        '！': '!',
        '、': ', ',
        '：': ': ',
        '；': '; ',
        '“': ' “',
        '”': '” ',
        '（': ' (',
        '）': ') ',
        '《': ' «',
        '》': '» ',
    }

    i = 0
    n = len(marked)
    while i < n:
        ch = marked[i]
        if ch == '\x00':
            end = marked.index('\x01', i)
            idx = int(marked[i + 1:end])
            tokens.append(('word', replacements[idx]))
            i = end + 1
            continue
        if ch in PUNCT_MAP:
            tokens.append(('punct', PUNCT_MAP[ch]))
            i += 1
            continue
        if ch.isascii():
            # Keep ASCII letters/digits together
            j = i
            while j < n and marked[j].isascii() and not marked[j].isspace():
                j += 1
            seg = marked[i:j].strip()
            if seg:
                tokens.append(('word', seg))
            i = j + (1 if j < n and marked[j].isspace() else 0)
            continue

        # Greedy longest match from lex
        matched = None
        for length in range(min(max_len, n - i), 1, -1):
            sub = marked[i:i + length]
            if sub in lex:
                matched = (length, lex[sub])
                break
        if matched:
            length, py = matched
            tokens.append(('word', py))
            i += length
        else:
            py = char_py.get(ch, ch)
            tokens.append(('word', py))
            i += 1

    # Join tokens cleanly with spacing rules
    parts: list[str] = []
    for kind, val in tokens:
        if kind == 'punct':
            if val in ('.', '?', '!', ', ', ': ', '; ', '” ', ') ', '» '):
                # Strip trailing space before closing/mid punct
                if parts and parts[-1] == ' ':
                    parts.pop()
                parts.append(val)
            else:
                if parts and not parts[-1].endswith((' ', '“', '(')):
                    parts.append(' ')
                parts.append(val.lstrip())
        else:
            if parts and not parts[-1].endswith((' ', '“', '(', '«')):
                parts.append(' ')
            parts.append(val)

    res = ''.join(parts)
    res = re.sub(r'\s+([,.?!:;”)])', r'\1', res)
    res = re.sub(r'([“()])\s+', r'\1', res)
    res = re.sub(r'\s{2,}', ' ', res).strip()
    return _capitalize_pinyin(res)
